"""
Compiles the Dataform project (definitions/) into ONE BigQuery script,
analysis/bigquery_build.sql, that can be pasted into the BigQuery console and run.

The script does what `dataform run` does, in dependency order:
  1. creates the `staging` and `gold` datasets,
  2. builds every staging view and gold table/view (with partitioning and clustering),
  3. runs every assertion as a BigQuery ASSERT statement (custom assertions plus
     the uniqueKey / nonNull / rowConditions declared in each config block):
     the script stops at the first failing check,
  4. writes the etl_run_log row (the Looker datagroup trigger),
  5. returns the four answers (analysis/answers.sql).

Usage:
  python3 analysis/build_bigquery_script.py [--project ID] [--raw-dataset NAME] [--location us-central1]
"""
import argparse
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

p = argparse.ArgumentParser()
p.add_argument("--project", default="control-electoral-510800")
p.add_argument("--raw-dataset", default="looker")
p.add_argument("--location", default="US", help="must match the location of the raw dataset")
p.add_argument("--min-group-size", default="5")
args = p.parse_args()

RAW_TABLES = ["payroll_lines", "employees", "departments", "employer_contributions", "budget"]


def split_config(text):
    start = text.index("config {")
    depth, i = 0, start + len("config ")
    while True:
        if text[i] == "{":
            depth += 1
        elif text[i] == "}":
            depth -= 1
            if depth == 0:
                break
        i += 1
    return text[start:i + 1], text[i + 1:]


def parse_config(cfg):
    def lst(key):
        m = re.search(key + r":\s*\[([^\]]*)\]", cfg)
        return re.findall(r'"(\w+)"', m.group(1)) if m else []
    out = {
        "type": re.search(r'type:\s*"(\w+)"', cfg).group(1),
        "schema": (re.search(r'schema:\s*"(\w+)"', cfg) or [None, None])[1],
        "partitionBy": (re.search(r'partitionBy:\s*"([^"]+)"', cfg) or [None, None])[1],
        "clusterBy": lst("clusterBy"),
        "uniqueKey": lst("uniqueKey"),
        "nonNull": lst("nonNull"),
    }
    m = re.search(r"rowConditions:\s*\[(.*?)\]", cfg, re.S)
    out["rowConditions"] = re.findall(r'["`](.+?)["`]', m.group(1)) if m else []
    return out


objects = {}
for folder in ["staging", "gold", "assertions"]:
    for f in sorted(os.listdir(os.path.join(ROOT, "definitions", folder))):
        cfg, body = split_config(open(os.path.join(ROOT, "definitions", folder, f)).read())
        c = parse_config(cfg)
        objects[f[:-5]] = {"cfg": c, "body": body.strip(), "deps": set(re.findall(r'ref\("(\w+)"\)', body)),
                           "dataset": c["schema"] or ("dataform_assertions" if c["type"] == "assertion" else "gold")}


def fq(name):
    if name in RAW_TABLES:
        return f"`{args.project}.{args.raw_dataset}.{name}`"
    return f"`{args.project}.{objects[name]['dataset']}.{name}`"


def resolve(sql):
    sql = sql.replace("${dataform.projectConfig.vars.min_group_size}", args.min_group_size)
    return re.sub(r'\$\{ref\("(\w+)"\)\}', lambda m: fq(m.group(1)), sql)


# dependency order (same rule as Dataform: an action runs after everything it refs)
order, built = [], set(RAW_TABLES)
while len(order) < len(objects):
    ready = [n for n, o in objects.items() if n not in built and o["deps"] <= built]
    if not ready:
        raise SystemExit(f"Unresolved dependencies: {set(objects) - built}")
    for n in sorted(ready, key=lambda n: objects[n]["cfg"]["type"] == "assertion"):
        order.append(n)
        built.add(n)

out = [
    "-- =============================================================================",
    "-- GENERATED by analysis/build_bigquery_script.py from definitions/ - do not edit.",
    f"-- Project: {args.project} | raw dataset: {args.raw_dataset} | location: {args.location}",
    "-- Paste into the BigQuery console and Run. Each ASSERT stops the script if a",
    "-- data-quality check fails; the last statements return the four answers.",
    "-- =============================================================================",
    "",
    f"CREATE SCHEMA IF NOT EXISTS `{args.project}.staging` OPTIONS (location = '{args.location}');",
    f"CREATE SCHEMA IF NOT EXISTS `{args.project}.gold` OPTIONS (location = '{args.location}');",
    "",
]

for name in order:
    o, c = objects[name], objects[name]["cfg"]
    sql = resolve(o["body"])
    if c["type"] == "assertion":
        out += [f"-- assertion: {name}", f"ASSERT NOT EXISTS (\n{sql}\n) AS '{name} failed';", ""]
        continue
    if c["type"] == "view":
        out += [f"-- view: {name}", f"CREATE OR REPLACE VIEW {fq(name)} AS\n{sql}\n;", ""]
    else:
        opts = ""
        if c["partitionBy"]:
            opts += f"\nPARTITION BY {c['partitionBy']}"
        if c["clusterBy"]:
            opts += f"\nCLUSTER BY {', '.join(c['clusterBy'])}"
        out += [f"-- table: {name}", f"CREATE OR REPLACE TABLE {fq(name)}{opts} AS\n{sql}\n;", ""]
    if c["uniqueKey"]:
        k = ", ".join(c["uniqueKey"])
        out.append(f"ASSERT NOT EXISTS (SELECT {k} FROM {fq(name)} GROUP BY {k} HAVING COUNT(*) > 1) "
                   f"AS '{name}: uniqueKey({k}) failed';")
    for col in c["nonNull"]:
        out.append(f"ASSERT NOT EXISTS (SELECT 1 FROM {fq(name)} WHERE {col} IS NULL) "
                   f"AS '{name}: nonNull({col}) failed';")
    for cond in c["rowConditions"]:
        cond = cond.replace("${dataform.projectConfig.vars.min_group_size}", args.min_group_size)
        out.append(f"ASSERT NOT EXISTS (SELECT 1 FROM {fq(name)} WHERE NOT ({cond})) "
                   f"AS '{name}: rowCondition failed';")
    out.append("")

# operations: etl_run_log (written only if every statement above succeeded)
ops = open(os.path.join(ROOT, "definitions", "operations", "etl_run_log.sqlx")).read()
_, ops_body = split_config(ops)
ops_body = ops_body.replace("${self()}", f"`{args.project}.gold.etl_run_log`")
out += ["-- operations: etl_run_log (Looker datagroup trigger)", resolve(ops_body.strip()), ""]

# answers
answers = open(os.path.join(ROOT, "analysis", "answers.sql")).read()
out += ["-- =============================== ANSWERS ===============================",
        resolve(answers.split("\n\n", 1)[1].strip()) if "\n\n" in answers else resolve(answers)]

path = os.path.join(ROOT, "analysis", "bigquery_build.sql")
open(path, "w").write("\n".join(out) + "\n")
n_assert = sum(1 for line in out if line.startswith("ASSERT") or "ASSERT NOT EXISTS (" in line)
print(f"wrote {path}: {len(order)} actions, {n_assert} ASSERT statements")
